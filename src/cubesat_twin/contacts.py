"""Ground-station contacts and the DTN contact plan.

A DTN node does not assume an end-to-end path: it stores bundles and forwards
them when a link exists. In space the links are predictable, because they
follow from the orbit, so the network can be told in advance when each link
will be up. That schedule is the *contact plan*, and Contact Graph Routing
(CGR) uses it to decide where and when to forward each bundle.

This module computes when the spacecraft is above the minimum elevation of
each ground station and writes the result as an ION contact plan
(`a contact` and `a range` commands), the format read by NASA/JPL's ION and
by the C++ bundle agent in `dtn-agent/`.
"""
import sys
from dataclasses import dataclass
from datetime import datetime

import numpy as np
import pandas as pd
import yaml
from skyfield.api import EarthSatellite, load, wgs84

SPEED_OF_LIGHT_KM_S = 299_792.458


@dataclass
class GroundStation:
    name: str
    node: int
    lat_deg: float
    lon_deg: float
    alt_m: float = 0.0


def load_stations(path: str) -> tuple[int, list[GroundStation]]:
    """Read the ground-station file: (spacecraft node number, stations)."""
    with open(path) as f:
        cfg = yaml.safe_load(f)
    return cfg.get("spacecraft_node", 1), [GroundStation(**s) for s in cfg["stations"]]


def station_geometry(name: str, line1: str, line2: str, times: pd.Series,
                     stations: list[GroundStation]) -> tuple[np.ndarray, np.ndarray]:
    """Elevation [deg] and slant range [km] of the spacecraft seen from each
    station, at each time. Both arrays have shape (n_stations, n_times)."""
    ts = load.timescale()
    sat = EarthSatellite(line1, line2, name, ts)
    t = ts.from_datetimes(pd.to_datetime(times, utc=True).dt.to_pydatetime())
    elevation = np.empty((len(stations), len(t)))
    distance = np.empty_like(elevation)
    for i, gs in enumerate(stations):
        site = wgs84.latlon(gs.lat_deg, gs.lon_deg, elevation_m=gs.alt_m)
        alt, _, dist = (sat - site).at(t).altaz()
        elevation[i], distance[i] = alt.degrees, dist.km
    return elevation, distance


def visible_station(elevation: np.ndarray, min_elevation_deg: float) -> np.ndarray:
    """Index of the station the spacecraft talks to at each step, or -1.

    With one radio the spacecraft can serve one station at a time; when two
    stations see it, it picks the one with the higher elevation (shorter
    path, better link margin).
    """
    best = elevation.argmax(axis=0)
    above = elevation.max(axis=0) >= min_elevation_deg
    return np.where(above, best, -1)


def find_contacts(times: pd.Series, station_idx: np.ndarray, elevation: np.ndarray,
                  distance: np.ndarray, stations: list[GroundStation],
                  step_s: float) -> pd.DataFrame:
    """Group consecutive steps with the same station into contacts.

    Times are resolved to one simulation step: each step stands for the
    interval [t, t + step) that follows it.
    """
    rows = []
    n = len(station_idx)
    k = 0
    while k < n:
        s = station_idx[k]
        if s < 0:
            k += 1
            continue
        j = k
        while j + 1 < n and station_idx[j + 1] == s:
            j += 1
        start = times.iloc[k]
        rows.append({
            "station": stations[s].name,
            "node": stations[s].node,
            "start": start,
            "end": times.iloc[j] + pd.Timedelta(seconds=step_s),
            "duration_min": (j - k + 1) * step_s / 60,
            "max_elevation_deg": float(elevation[s, k:j + 1].max()),
            "min_range_km": float(distance[s, k:j + 1].min()),
        })
        k = j + 1
    return pd.DataFrame(rows, columns=["station", "node", "start", "end", "duration_min",
                                       "max_elevation_deg", "min_range_km"])


def ion_contact_plan(contacts: pd.DataFrame, plan_start: datetime, spacecraft_node: int,
                     downlink_bytes_s: float, uplink_bytes_s: float) -> str:
    """ION contact plan for the contacts, with times relative to plan_start.

    Each pass gives two contacts (downlink and uplink) and one range entry,
    with the one-way light time rounded up to a whole second as ION expects.
    """
    t0 = pd.Timestamp(plan_start)
    t0 = t0.tz_localize("UTC") if t0.tzinfo is None else t0
    lines = [
        "# Contact plan generated by the CubeSat power digital twin.",
        f"# Times are seconds after {t0.isoformat()}; rates are bytes/s.",
        f"# Spacecraft node {spacecraft_node}; ground stations: "
        + ", ".join(f"{name}={node}" for name, node in
                    contacts[["station", "node"]].drop_duplicates().itertuples(index=False)),
    ]
    for c in contacts.itertuples():
        a = int(round((c.start - t0).total_seconds()))
        b = int(round((c.end - t0).total_seconds()))
        owlt = max(1, int(np.ceil(c.min_range_km / SPEED_OF_LIGHT_KM_S)))
        lines.append(f"a contact +{a} +{b} {spacecraft_node} {c.node} {int(downlink_bytes_s)}")
        lines.append(f"a contact +{a} +{b} {c.node} {spacecraft_node} {int(uplink_bytes_s)}")
        lines.append(f"a range +{a} +{b} {spacecraft_node} {c.node} {owlt}")
    return "\n".join(lines) + "\n"


def contact_summary(contacts: pd.DataFrame, days: float) -> dict:
    """Contact statistics: how often and how long the spacecraft can talk to
    the ground, and the longest wait between two contacts."""
    if contacts.empty:
        return {"contacts": 0, "contacts_per_day": 0.0, "mean_contact_min": 0.0,
                "contact_min_per_day": 0.0, "max_gap_h": round(days * 24, 2)}
    gaps = (contacts.start.iloc[1:].values - contacts.end.iloc[:-1].values) / np.timedelta64(1, "h")
    return {
        "contacts": len(contacts),
        "contacts_per_day": round(len(contacts) / days, 2),
        "mean_contact_min": round(float(contacts.duration_min.mean()), 1),
        "contact_min_per_day": round(float(contacts.duration_min.sum()) / days, 1),
        "max_gap_h": round(float(gaps.max()), 2) if len(gaps) else 0.0,
        "per_station": contacts.groupby("station").size().to_dict(),
    }


if __name__ == "__main__":
    from orbit import read_tle

    cfg_path = sys.argv[1] if len(sys.argv) > 1 else "configs/cubesat_1u.yaml"
    with open(cfg_path) as f:
        cfg = yaml.safe_load(f)
    dtn = cfg["dtn"]
    name, l1, l2 = read_tle(cfg["satellite"]["tle_file"])
    sc_node, stations = load_stations(dtn["ground_stations"])
    sim = cfg["simulation"]
    start = datetime.fromisoformat(sim["start"])
    times = pd.Series(pd.date_range(start, periods=int(sim["duration_days"] * 86400 / sim["step_s"]),
                                    freq=f"{sim['step_s']}s", tz="UTC"))
    el, dist = station_geometry(name, l1, l2, times, stations)
    idx = visible_station(el, dtn["min_elevation_deg"])
    contacts = find_contacts(times, idx, el, dist, stations, sim["step_s"])
    for key, value in contact_summary(contacts, sim["duration_days"]).items():
        print(f"{key:>20}: {value}")
    plan = ion_contact_plan(contacts, start, sc_node, dtn["downlink_bps"] / 8, dtn["uplink_bps"] / 8)
    with open("results/contact_plan.ion", "w") as f:
        f.write(plan)
    print("Saved results/contact_plan.ion")
